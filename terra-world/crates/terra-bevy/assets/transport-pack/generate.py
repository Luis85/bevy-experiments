#!/usr/bin/env python3
"""Author Terra's original Comet transport GLB, runtime pack and composed recipe.

Python standard library only. No downloaded art, fonts or texture dependencies.
MIT OR Apache-2.0. Metres, +Y up, -Z forward; wheels rest on Y=0.
Use --check to verify every generated byte without changing any source file.
"""
import argparse
import copy
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def unit(a):
    n = math.sqrt(sum(v * v for v in a))
    return [v / n for v in a]


def quat_x(angle):
    return [math.sin(angle / 2), 0, 0, math.cos(angle / 2)]


class Model:
    def __init__(self):
        self.binary = bytearray()
        self.gltf = {
            "asset": {"version": "2.0", "generator": "Terra original Comet authoring pipeline"},
            "scene": 0,
            "scenes": [{"name": "Comet hatchback", "nodes": [0]}],
            "nodes": [{"name": "comet", "children": []}],
            "meshes": [], "materials": [], "buffers": [],
            "bufferViews": [], "accessors": [], "animations": [],
        }

    def accessor(self, values, width, bounds=False):
        self.binary.extend(b"\0" * (-len(self.binary) % 4))
        offset = len(self.binary)
        flat = [n for row in values for n in (row if isinstance(row, (tuple, list)) else [row])]
        self.binary.extend(struct.pack("<" + "f" * len(flat), *flat))
        view = len(self.gltf["bufferViews"])
        self.gltf["bufferViews"].append({"buffer": 0, "byteOffset": offset, "byteLength": len(self.binary) - offset})
        item = {"bufferView": view, "componentType": 5126, "count": len(values), "type": {1: "SCALAR", 3: "VEC3", 4: "VEC4"}[width]}
        if bounds:
            rows = values if width > 1 else [[v] for v in values]
            item["min"] = [min(row[i] for row in rows) for i in range(width)]
            item["max"] = [max(row[i] for row in rows) for i in range(width)]
        self.gltf["accessors"].append(item)
        return len(self.gltf["accessors"]) - 1

    def material(self, name, color, roughness=0.65, metal=0.0):
        item = {"name": name, "pbrMetallicRoughness": {"baseColorFactor": color, "metallicFactor": metal, "roughnessFactor": roughness}}
        if color[3] < 1:
            item.update({"alphaMode": "BLEND", "doubleSided": True})
        self.gltf["materials"].append(item)
        return len(self.gltf["materials"]) - 1

    def node(self, name, parent=0, position=(0, 0, 0)):
        n = len(self.gltf["nodes"])
        self.gltf["nodes"].append({"name": name, "translation": list(position), "children": []})
        self.gltf["nodes"][parent]["children"].append(n)
        return n

    def mesh(self, name, triangles, material, parent=0):
        vertices, normals = [], []
        for a, b, c in triangles:
            normal = cross([b[i] - a[i] for i in range(3)], [c[i] - a[i] for i in range(3)])
            length = math.sqrt(sum(v * v for v in normal))
            if length < 1e-10:
                continue
            normal = [v / length for v in normal]
            vertices.extend((a, b, c))
            normals.extend((normal, normal, normal))
        p = self.accessor(vertices, 3, True)
        n = self.accessor(normals, 3)
        mesh = len(self.gltf["meshes"])
        self.gltf["meshes"].append({"name": name + "-geometry", "primitives": [{"attributes": {"POSITION": p, "NORMAL": n}, "material": material}]})
        node = self.node(name, parent)
        self.gltf["nodes"][node]["mesh"] = mesh
        return node

    def faces(self, name, vertices, faces, material, parent=0):
        triangles = []
        for face in faces:
            for i in range(1, len(face) - 1):
                triangles.append((vertices[face[0]], vertices[face[i]], vertices[face[i + 1]]))
        return self.mesh(name, triangles, material, parent)

    def box(self, name, center, size, material, parent=0):
        x, y, z = center
        w, h, d = [v / 2 for v in size]
        vertices = [(x - w, y - h, z - d), (x + w, y - h, z - d), (x + w, y + h, z - d), (x - w, y + h, z - d),
                    (x - w, y - h, z + d), (x + w, y - h, z + d), (x + w, y + h, z + d), (x - w, y + h, z + d)]
        return self.faces(name, vertices, [(0, 3, 2, 1), (4, 5, 6, 7), (0, 4, 7, 3), (1, 2, 6, 5), (0, 1, 5, 4), (3, 7, 6, 2)], material, parent)

    def beam(self, name, start, end, radius, material, parent=0):
        along = unit([end[i] - start[i] for i in range(3)])
        a = unit(cross(along, [1, 0, 0] if abs(along[0]) < .9 else [0, 1, 0]))
        b = cross(along, a)
        vertices = [[point[i] + radius * (sa * a[i] + sb * b[i]) for i in range(3)]
                    for point in [start, end] for sa, sb in [(-1, -1), (1, -1), (1, 1), (-1, 1)]]
        return self.faces(name, vertices, [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)], material, parent)

    def radial(self, name, profile, material, parent=0, sides=20):
        vertices = [(x, radius * math.cos(i * math.tau / sides), radius * math.sin(i * math.tau / sides))
                    for x, radius in profile for i in range(sides)]
        faces = []
        for j in range(len(profile) - 1):
            for i in range(sides):
                n = (i + 1) % sides
                faces.append((j * sides + i, j * sides + n, (j + 1) * sides + n, (j + 1) * sides + i))
        return self.faces(name, vertices, faces, material, parent)

    def animation(self, name, duration, tracks):
        times = [duration * i / 24 for i in range(25)]
        input_index = self.accessor(times, 1, True)
        channels, samplers = [], []
        for node, fn in tracks:
            output = self.accessor([fn(i / 24) for i in range(25)], 4)
            channels.append({"sampler": len(samplers), "target": {"node": node, "path": "rotation"}})
            samplers.append({"input": input_index, "output": output, "interpolation": "LINEAR"})
        self.gltf["animations"].append({"name": name, "samplers": samplers, "channels": channels})

    def bytes(self):
        self.gltf["buffers"] = [{"byteLength": len(self.binary)}]
        for node in self.gltf["nodes"]:
            if not node.get("children"):
                node.pop("children", None)
        text = json.dumps(self.gltf, separators=(",", ":"), allow_nan=False).encode()
        text += b" " * (-len(text) % 4)
        binary = bytes(self.binary) + b"\0" * (-len(self.binary) % 4)
        return (struct.pack("<4sII", b"glTF", 2, 28 + len(text) + len(binary))
                + struct.pack("<I4s", len(text), b"JSON") + text
                + struct.pack("<I4s", len(binary), b"BIN\0") + binary)


def build():
    m = Model()
    paint = m.material("original-petrol-teal-livery", [.07, .33, .34, 1], .35, .24)
    roof = m.material("warm-ivory-roof", [.81, .79, .67, 1], .42, .08)
    rubber = m.material("tire-rubber", [.035, .041, .043, 1], .94)
    trim = m.material("charcoal-trim", [.075, .095, .105, 1], .72)
    metal = m.material("brushed-alloy", [.56, .61, .63, 1], .31, .65)
    seats = m.material("woven-sand-seats", [.37, .30, .23, 1], .93)
    glass = m.material("cool-clear-glazing", [.25, .44, .48, .29], .16, .06)
    lamp = m.material("ivory-headlamp-lens", [.94, .89, .63, 1], .25)
    red = m.material("rear-lamp-lens", [.60, .065, .045, 1], .26)
    gauge = m.material("dashboard-display", [.31, .58, .42, 1], .6)

    # A bevelled, tapered original shell stays inside the Comet's existing
    # 1.9 x 1.65 x 4.2 metre authority envelope. No collision asset is exported.
    rings = [(-2.07, .72, .48, .70), (-1.82, .87, .38, .84), (-.97, .88, .38, .90),
             (.99, .88, .38, .90), (1.77, .84, .42, .87), (2.04, .73, .47, .78)]
    vertices = []
    for z, width, low, high in rings:
        vertices.extend([(-width + .08, low, z), (width - .08, low, z), (width, low + .09, z),
                         (width, high - .06, z), (width - .07, high, z), (-width + .07, high, z),
                         (-width, high - .06, z), (-width, low + .09, z)])
    faces = [tuple(reversed(range(8))), tuple((len(rings) - 1) * 8 + i for i in range(8))]
    for j in range(len(rings) - 1):
        for i in range(8):
            faces.append((j * 8 + i, j * 8 + (i + 1) % 8, (j + 1) * 8 + (i + 1) % 8, (j + 1) * 8 + i))
    m.faces("painted-shell", vertices, faces, paint)
    m.box("floor", (0, .51, .1), (1.55, .10, 2.45), trim)
    m.box("roof-panel", (0, 1.58, .26), (1.43, .09, 1.78), roof)
    m.box("front-bumper", (0, .51, -2.07), (1.48, .16, .045), trim)
    m.box("rear-bumper", (0, .51, 2.065), (1.48, .16, .045), trim)
    m.box("front-grille", (0, .67, -2.084), (.59, .14, .018), trim)
    m.box("front-badge", (0, .79, -1.95), (.09, .03, .12), metal)
    m.box("rear-plate", (0, .69, 2.064), (.34, .11, .018), roof)

    # Glazing is separate from the cabin: the four actual seat positions are
    # visible through it. Empty seats are not claims about saved passengers.
    m.faces("windscreen", [(-.80, .91, -.94), (.80, .91, -.94), (.68, 1.535, -.59), (-.68, 1.535, -.59)], [(0, 3, 2, 1)], glass)
    m.faces("rear-window", [(-.81, .91, 1.43), (.81, .91, 1.43), (.68, 1.535, 1.10), (-.68, 1.535, 1.10)], [(0, 1, 2, 3)], glass)
    for sign, side in [(-1, "left"), (1, "right")]:
        bottom, top = sign * .835, sign * .715
        points = [(bottom, .92, -.86), (bottom, .92, 1.37), (top, 1.52, 1.07), (top, 1.52, -.57)]
        m.faces(side + "-side-glazing", points, [(0, 1, 2, 3) if sign < 0 else (3, 2, 1, 0)], glass)
        for name, a, b in [("a-pillar", (sign * .80, .90, -.94), (sign * .70, 1.57, -.60)),
                           ("c-pillar", (sign * .81, .90, 1.43), (sign * .70, 1.57, 1.11)),
                           ("b-pillar", (sign * .84, .91, .24), (sign * .715, 1.55, .24))]:
            m.beam(side + "-" + name, a, b, .035 if name != "b-pillar" else .025, paint)
        m.box(side + "-sill", (sign * .88, .52, .18), (.025, .10, 2.25), trim)
        m.box(side + "-door-handle", (sign * .886, .86, .09), (.024, .035, .16), metal)
        m.box(side + "-rear-handle", (sign * .886, .86, 1.14), (.024, .035, .16), metal)
        m.box(side + "-mirror-housing", (sign * .91, 1.02, -.73), (.078, .105, .18), paint)
        m.box(side + "-mirror", (sign * .91, 1.025, -.63), (.067, .078, .012), metal)
        m.box(side + "-headlamp", (sign * .59, .73, -2.015), (.29, .105, .035), lamp)
        m.box(side + "-tail-lamp", (sign * .61, .75, 2.028), (.22, .14, .025), red)
        for row, z in [("front", -.24), ("rear", .74)]:
            x = sign * .42
            m.box(side + "-" + row + "-seat-base", (x, .65, z), (.46, .14, .47), seats)
            m.box(side + "-" + row + "-seat-back", (x, .92, z + .20), (.44, .45, .12), seats)
            m.box(side + "-" + row + "-headrest", (x, 1.23, z + .21), (.25, .18, .11), seats)
    m.box("dashboard", (0, .94, -.68), (1.42, .17, .24), trim)
    m.box("instrument-cluster", (-.42, 1.04, -.67), (.30, .08, .035), gauge)
    m.box("center-console", (0, .79, -.25), (.18, .21, .49), trim)
    m.box("console-display", (0, 1.055, -.61), (.16, .11, .025), gauge)
    steering_wheel = m.node("cabin-steering-wheel", position=(-.42, 1.045, -.47))
    m.gltf["nodes"][steering_wheel]["rotation"] = [0, math.sin(math.pi / 4), 0, math.cos(math.pi / 4)]
    m.radial("cabin-steering-rim", [(-.017, .12), (-.017, .16), (.017, .16), (.017, .12), (-.017, .12)], trim, steering_wheel, 16)

    wheel_nodes, wheel_names, steering_names = [], [], []
    for front, z in [(True, -1.32), (False, 1.23)]:
        for sign, side in [(-1, "left"), (1, "right")]:
            name = ("front" if front else "rear") + "_" + side
            pivot = m.node(name + "_mount", position=(sign * .82, .31, z))
            if front:
                steer_name = name + "_steer"
                pivot = m.node(steer_name, pivot)
                steering_names.append(steer_name)
            wheel_name = name + "_wheel"
            wheel = m.node(wheel_name, pivot)
            wheel_nodes.append(wheel)
            wheel_names.append(wheel_name)
            m.radial(name + "-tire", [(-.10, .19), (-.10, .27), (-.065, .31), (.065, .31), (.10, .27), (.10, .19), (-.10, .19)], rubber, wheel)
            m.radial(name + "-alloy", [(-.103, 0), (-.103, .185), (.103, .185), (.103, 0)], metal, wheel)
            for i in range(5):
                angle = i * math.tau / 5
                # Visible spokes give the rolling animation an unambiguous phase.
                a = (sign * .106, .055 * math.cos(angle), .055 * math.sin(angle))
                b = (sign * .106, .16 * math.cos(angle), .16 * math.sin(angle))
                m.beam(name + "-spoke-" + str(i), a, b, .017, trim, wheel)
    antenna = m.node("antenna_pivot", position=(0, 1.625, .95))
    m.beam("short-antenna", (0, 0, 0), (0, .022, .11), .008, trim, antenna)
    m.animation("parked", 2., [(node, lambda _t: quat_x(0.)) for node in wheel_nodes])
    m.animation("rolling", 1., [(node, lambda t: quat_x(-math.tau * t)) for node in wheel_nodes]
                + [(antenna, lambda t: quat_x(.035 * math.sin(t * math.tau)))])
    data = m.bytes()
    policy = {"idle": "parked", "walk": "rolling", "run": "rolling", "feed": "parked", "drink": "parked",
              "walk_speed_m_s": 2., "run_speed_m_s": 10., "blend_seconds": .18,
              "vehicle_motion": {"wheel_radius_m": .31, "wheels": wheel_names, "steering": steering_names}}
    binding = {"target": {"type": "vehicle_model", "value": "compact"}, "model": "comet", "scale": 1,
               "ground_offset_m": 0, "yaw_offset_degrees": 0, "animation": policy}
    manifest = {"schema_version": 1, "name": "Terra Comet transport example", "author": "Terra World contributors",
                "license": "MIT OR Apache-2.0", "models": [{"id": "comet", "file": "comet.glb", "sha256": hashlib.sha256(data).hexdigest(), "scene": 0}],
                "bindings": [binding]}
    recipe = json.loads((ROOT.parent / "wildlife-authoring.recipe.json").read_text())
    recipe = copy.deepcopy(recipe)
    recipe["name"] = "Terra woodland and Comet authoring example"
    recipe["models"].append({"id": "comet", "source": "transport-pack/comet.glb", "scene": 0,
                             "provenance": "Original Terra World contributors Comet mesh, cabin and animation, authored by transport-pack/generate.py; MIT OR Apache-2.0. No third-party art. Fixed example livery; no occupancy or boarding animation."})
    recipe["bindings"].append(binding)
    demo = copy.deepcopy(json.loads((ROOT.parent / "wildlife-pack/pack.json").read_text()))
    demo["name"] = "Terra woodland and Comet demo"
    for model in demo["models"]:
        model["file"] = "wildlife-pack/" + model["file"]
    demo["models"].append({**manifest["models"][0], "file": "transport-pack/comet.glb"})
    demo["bindings"].append(binding)
    outputs = {ROOT / "comet.glb": data,
               ROOT / "pack.json": (json.dumps(manifest, indent=2) + "\n").encode(),
               ROOT.parent / "transport-demo.pack.json": (json.dumps(demo, indent=2) + "\n").encode(),
               ROOT.parent / "transport-authoring.recipe.json": (json.dumps(recipe, indent=2) + "\n").encode()}
    return outputs, len(m.gltf["nodes"]), len(m.gltf["meshes"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated bytes without writing")
    args = parser.parse_args()
    outputs, nodes, meshes = build()
    for path, data in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit("Generated content differs: " + str(path))
        else:
            path.write_bytes(data)
    print(json.dumps({"status": "matched" if args.check else "generated", "files": len(outputs), "nodes": nodes, "meshes": meshes,
                      "glb_bytes": len(outputs[ROOT / "comet.glb"]), "glb_sha256": hashlib.sha256(outputs[ROOT / "comet.glb"]).hexdigest()}, indent=2))


if __name__ == "__main__":
    main()
