use std::collections::BTreeMap;
use terra_core::{
    FeatureKind, GeoPosition, HeightField, SourceRecord, TileKey, WorldChunk, WorldFeature,
};

/// Continuous, deterministic synthetic surface. Longitude-periodic and continuous
/// at the poles, so neighbouring geographic chunks share their sampled edges.
/// This intentionally does not claim to reproduce real geography.
pub fn procedural_height(position: GeoPosition, seed: u64) -> f32 {
    let latitude = position.latitude.to_radians();
    let longitude = position.longitude.to_radians();
    let phase = (seed % 10_000) as f64 * 0.017;
    let continental = latitude.cos().powi(2)
        * ((longitude * 7.0 + phase).sin() * 65.0 + (latitude * 11.0).cos() * 55.0);
    let local =
        latitude.cos().powi(2) * ((longitude * 8_000.0).sin() * (latitude * 9_000.0).cos() * 24.0);
    (120.0 + continental + local) as f32
}

/// Fully local example world; all generated content is explicitly synthetic.
pub fn procedural_chunk(key: TileKey, resolution: usize, seed: u64) -> WorldChunk {
    let resolution = resolution.clamp(2, 257);
    let bounds = key.bounds();
    let position = |u: f64, v: f64| {
        let longitude = bounds.west + (bounds.east - bounds.west) * u;
        let latitude = bounds.north - (bounds.north - bounds.south) * v;
        let mut p = GeoPosition {
            latitude,
            longitude,
            altitude_m: 0.0,
        };
        p.altitude_m = procedural_height(p, seed) as f64;
        p
    };
    let samples_m = (0..resolution)
        .flat_map(|row| {
            let position = &position;
            (0..resolution).map(move |column| {
                position(
                    column as f64 / (resolution - 1) as f64,
                    row as f64 / (resolution - 1) as f64,
                )
                .altitude_m as f32
            })
        })
        .collect();
    let mut features = Vec::new();
    let mut add = |suffix: &str, kind: FeatureKind, coordinates: &[(f64, f64)], height: f32| {
        features.push(WorldFeature {
            id: format!("synthetic:{}:{}:{}:{suffix}", key.level, key.x, key.y),
            kind,
            points: coordinates.iter().map(|&(u, v)| position(u, v)).collect(),
            height_m: height,
            properties: BTreeMap::from([("synthetic".into(), "true".into())]),
        });
    };
    add("road", FeatureKind::Road, &[(0.0, 0.52), (1.0, 0.52)], 4.0);
    add("path", FeatureKind::Road, &[(0.48, 0.0), (0.48, 1.0)], 2.0);
    add(
        "farm",
        FeatureKind::Farm,
        &[
            (0.06, 0.08),
            (0.36, 0.08),
            (0.36, 0.36),
            (0.06, 0.36),
            (0.06, 0.08),
        ],
        0.0,
    );
    add(
        "wood",
        FeatureKind::Forest,
        &[
            (0.66, 0.08),
            (0.94, 0.08),
            (0.94, 0.35),
            (0.66, 0.35),
            (0.66, 0.08),
        ],
        9.0,
    );
    add(
        "pond",
        FeatureKind::Water,
        &[
            (0.65, 0.72),
            (0.92, 0.68),
            (0.94, 0.9),
            (0.74, 0.94),
            (0.65, 0.72),
        ],
        0.0,
    );
    for i in 0..5 {
        let u = 0.08 + i as f64 * 0.075;
        add(
            &format!("building-{i}"),
            FeatureKind::Building,
            &[
                (u, 0.61),
                (u + 0.045, 0.61),
                (u + 0.045, 0.67),
                (u, 0.67),
                (u, 0.61),
            ],
            5.0 + (i % 3) as f32 * 3.0,
        );
    }
    for i in 0..12 {
        let u = 0.69 + (i % 4) as f64 * 0.07;
        let v = 0.12 + (i / 4) as f64 * 0.08;
        add(
            &format!("tree-{i}"),
            FeatureKind::Tree,
            &[(u, v)],
            7.0 + (i % 4) as f32 * 1.5,
        );
    }
    WorldChunk {
        key,
        heights:HeightField { width:resolution,height:resolution,samples_m },
        features,
        sources:vec![SourceRecord {
            provider:"Terra procedural example".into(),
            license:"MIT OR Apache-2.0".into(),
            attribution:"Synthetic demo content generated by Terra World; not real-world survey data".into(),
            url:"https://example.invalid/terra-world/synthetic".into(),
            retrieved_unix_seconds:0,
            synthetic:true,
        }],
        warnings:vec!["OFFLINE SYNTHETIC WORLD: geographic coordinates are real, terrain and features are generated examples.".into()],
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn adjacent_tiles_share_height_samples() {
        let west = procedural_chunk(
            TileKey {
                level: 14,
                x: 8800,
                y: 3900,
            },
            17,
            42,
        );
        let east = procedural_chunk(
            TileKey {
                level: 14,
                x: 8801,
                y: 3900,
            },
            17,
            42,
        );
        for row in 0..17 {
            assert_eq!(
                west.heights.samples_m[row * 17 + 16],
                east.heights.samples_m[row * 17]
            );
        }
    }
    #[test]
    fn antimeridian_and_poles_are_continuous() {
        let height = |lat, lon| {
            procedural_height(
                GeoPosition {
                    latitude: lat,
                    longitude: lon,
                    altitude_m: 0.0,
                },
                42,
            )
        };
        assert!((height(42.0, 180.0) - height(42.0, -180.0)).abs() < 0.001);
        assert_eq!(height(90.0, -177.0), height(90.0, 123.0));
    }
}
